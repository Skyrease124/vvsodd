// Assemble a Netlify project from SkyData's normal build (`npm run build` in SkyData_Website → dist/).
// Usage: node build.mjs <out-dir> <setup-code-file>
//   <out-dir>          the project folder to deploy (created fresh)
//   <setup-code-file>  where to write the one-time owner setup code; must be outside <out-dir>.
//                      If it already exists its code is reused, so rebuilding doesn't change the code.
import { build } from 'esbuild';
import { cpSync, existsSync, mkdirSync, readFileSync, readdirSync, rmSync, writeFileSync } from 'node:fs';
import { createHash, randomBytes } from 'node:crypto';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const site = path.resolve(here, '..');
const [outArg, codeArg] = process.argv.slice(2);
if (!outArg || !codeArg) throw new Error('Usage: node build.mjs <out-dir> <setup-code-file>');
const out = path.resolve(outArg);
const codeFile = path.resolve(codeArg);
if (codeFile.startsWith(out + path.sep)) throw new Error('The setup code file must be outside the deploy folder.');
const client = path.join(site, 'dist/client');
if (!existsSync(path.join(site, 'dist/server/index.js'))) throw new Error('Run `npm run build` in SkyData_Website first.');

// 1. Owner setup code: only its hash goes into the deploy.
let code = existsSync(codeFile) ? readFileSync(codeFile, 'utf8').trim() : '';
if (!/^[A-Z2-9]{4}(-[A-Z2-9]{4}){5}$/.test(code)) {
  const alphabet = 'ABCDEFGHJKLMNPQRSTUVWXYZ23456789';
  const bytes = randomBytes(24);
  code = Array.from(bytes, (b) => alphabet[b % 32]).join('').match(/.{4}/g).join('-');
  writeFileSync(codeFile, code + '\n', { mode: 0o600 });
}
const codeHash = createHash('sha256').update(code).digest('hex');

// 2. Protected downloads are served by the function (after the owner check), so they are embedded in it.
const downloadsDir = path.join(client, 'downloads');
const files = existsSync(downloadsDir) ? readdirSync(downloadsDir) : [];
writeFileSync(
  path.join(here, 'src/downloads.mjs'),
  '// Generated by build.mjs from dist/client/downloads. Served only through the site\'s owner checks.\n' +
    'const b = (s) => Uint8Array.from(Buffer.from(s, "base64"));\nexport const protectedDownloads = {\n' +
    files.map((f) => `  ${JSON.stringify(f)}: b(${JSON.stringify(readFileSync(path.join(downloadsDir, f)).toString('base64'))}),`).join('\n') +
    '\n};\n',
);

rmSync(out, { recursive: true, force: true });
mkdirSync(path.join(out, 'netlify/functions/skydata'), { recursive: true });

// 3. Static files: everything the CDN may serve publicly (not the protected downloads).
cpSync(client, path.join(out, 'public'), { recursive: true, filter: (src) => !src.startsWith(downloadsDir) });

// 4. The function: SkyData's server bundle + adapter, as one file.
await build({
  entryPoints: [path.join(here, 'src/function.mjs')],
  outfile: path.join(out, 'netlify/functions/skydata/server.mjs'),
  bundle: true,
  platform: 'node',
  format: 'esm',
  target: 'node22',
  external: ['pg-native'],
  define: { __SETUP_CODE_HASH__: JSON.stringify(codeHash) },
  banner: { js: "import { createRequire as __cr } from 'node:module'; const require = __cr(import.meta.url);" },
  legalComments: 'none',
  logLevel: 'warning',
});

// Netlify reads the route from the entry file's source, so it stays a literal here.
writeFileSync(
  path.join(out, 'netlify/functions/skydata/skydata.mjs'),
  "// Every request that isn't a static file goes to SkyData's server (server.mjs, built by netlify-adapter/build.mjs).\nexport { default } from './server.mjs';\n\nexport const config = {\n  path: '/*',\n  preferStatic: true,\n};\n",
);

// 5. Database tables, applied by Netlify before each production deploy goes live.
cpSync(path.join(here, 'migrations'), path.join(out, 'netlify/database/migrations'), { recursive: true });

// 6. Project settings. @netlify/database must be a dependency for Netlify to create the database.
const adapterPkg = JSON.parse(readFileSync(path.join(here, 'package.json'), 'utf8'));
writeFileSync(
  path.join(out, 'package.json'),
  JSON.stringify({ name: 'skydata', private: true, type: 'module', dependencies: { '@netlify/database': adapterPkg.dependencies['@netlify/database'], '@netlify/blobs': adapterPkg.dependencies['@netlify/blobs'] } }, null, 2) + '\n',
);
writeFileSync(
  path.join(out, 'netlify.toml'),
  `# SkyData on Netlify. Prebuilt: the pages are in public/, the server is one function.
[build]
  publish = "public"
  command = "echo 'SkyData is prebuilt'"

[functions]
  directory = "netlify/functions"
`,
);
console.log(JSON.stringify({ out, downloads: files.length, setupCodeFile: codeFile }));
