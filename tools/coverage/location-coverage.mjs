// Location coverage of the published map datasets. For each dataset in kinvest-liens/map/data it counts the records the
// published file places (cx), the records with a parcel outline (g), and the records it does not place, and it shows
// whether an official parcel source is configured for the county. Owner-approved positions are served from the server
// (netlify/lib/data/parcel-matches) and are not in the published file, so they appear in their own column.
//
//   node tools/coverage/location-coverage.mjs      rewrites docs/location-coverage.md and docs/location-coverage.csv
//
// tests/location-coverage.test.mjs fails when those documents are out of date.
import fs from 'node:fs';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
import {sourcesFor} from '../../netlify/lib/gis-sources.mjs';

export const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..', '..');
export const DATA_DIR = path.join(ROOT, 'kinvest-liens', 'map', 'data');
export const AUDIT_DIR = path.join(ROOT, 'netlify', 'lib', 'data', 'parcel-matches');
export const REGISTRY_FILE = path.join(ROOT, 'netlify', 'lib', 'data', 'florida-gis-registry.json');
export const MD_FILE = path.join(ROOT, 'docs', 'location-coverage.md');
export const CSV_FILE = path.join(ROOT, 'docs', 'location-coverage.csv');

const readJson = file => JSON.parse(fs.readFileSync(file, 'utf8'));
const sortKey = r => r.state + '|' + r.county + '|' + r.dataset;
const pct = (n, d) => (d ? Math.round((1000 * n) / d) / 10 : 0);
const cell = v => String(v ?? '').replace(/\|/g, '\\|');
const csvCell = v => (/[",\n]/.test(String(v ?? '')) ? '"' + String(v).replace(/"/g, '""') + '"' : String(v ?? ''));

// One row per published dataset file.
export function datasetRows(dataDir = DATA_DIR, auditDir = AUDIT_DIR, registryFile = REGISTRY_FILE) {
  const registry = fs.existsSync(registryFile) ? readJson(registryFile) : {counties: []};
  const rows = [];
  for (const f of fs.readdirSync(dataDir).filter(x => x.endsWith('.json')).sort()) {
    const ds = readJson(path.join(dataDir, f));
    const id = f.replace(/\.json$/, '');
    const recs = ds.recs || [];
    let located = 0, boundary = 0;
    for (const r of recs) {
      if (Array.isArray(r.cx) && r.cx.length === 2 && r.cx.every(Number.isFinite)) located++;
      if (Array.isArray(r.g) && r.g.length) boundary++;
    }
    const auditFile = path.join(auditDir, id + '.json');
    const audit = fs.existsSync(auditFile) ? readJson(auditFile) : null;
    const countyName = String(ds.county || '').replace(/ County$/, '');
    const reg = ds.state === 'FL' ? registry.counties.find(c => c.name === countyName) : null;
    rows.push({
      state: ds.state, county: ds.county, dataset: id, records: recs.length, located, boundary, unlocated: recs.length - located,
      sources: sourcesFor(ds.state, ds.county).map(s => s.id),
      server: audit ? {matched: audit.summary.matched, boundary: audit.summary.matchedWithBoundary, pending: audit.summary.pending} : null,
      florida: ds.state === 'FL' ? (reg ? 'listed (' + reg.countyEvidenceStatus + ')' : 'not listed') : '',
    });
  }
  return rows.sort((a, b) => (sortKey(a) < sortKey(b) ? -1 : sortKey(a) > sortKey(b) ? 1 : 0));
}

function totals(rows) {
  const t = {datasets: rows.length, records: 0, located: 0, boundary: 0, unlocated: 0};
  for (const r of rows) { t.records += r.records; t.located += r.located; t.boundary += r.boundary; t.unlocated += r.unlocated; }
  return t;
}

const n = x => x.toLocaleString('en-US');

// The two documents (Markdown and CSV) for a set of rows. Deterministic: no timestamps.
export function buildCoverage(rows = datasetRows()) {
  const t = totals(rows);
  const states = [...new Set(rows.map(r => r.state))].sort();
  const withSource = rows.filter(r => r.sources.length).length;
  const noLocated = rows.filter(r => r.located === 0).length;
  const noBoundary = rows.filter(r => r.located > 0 && r.boundary < r.located).length;
  const serverRows = rows.filter(r => r.server);
  const md = [];
  md.push('# Location coverage of the published map datasets', '');
  md.push('Generated by `node tools/coverage/location-coverage.mjs` from the published files in `kinvest-liens/map/data/`, the official parcel sources in `netlify/lib/gis-sources.mjs`, the owner-side audits in `netlify/lib/data/parcel-matches/` and the Florida registry in `netlify/lib/data/florida-gis-registry.json`. `tests/location-coverage.test.mjs` fails if this file is out of date.', '');
  md.push('- **Located**: records whose published file carries a position (`cx`). **Boundary**: records with a parcel outline (`g`). **Unlocated**: records with no position.');
  md.push('- Owner-approved positions are kept on the server until the 48-hour Pro early-access window ends. They are not in the published counts; the audit column shows them where an audit exists.');
  md.push('- These counts describe the files in the repository. They are not a live count of what a visitor sees.', '');
  md.push('## Totals', '');
  md.push('| Datasets | Records | Located | Boundary | Unlocated | Located % |', '|---|---|---|---|---|---|');
  md.push(`| ${n(t.datasets)} | ${n(t.records)} | ${n(t.located)} | ${n(t.boundary)} | ${n(t.unlocated)} | ${pct(t.located, t.records)} |`, '');
  md.push('## What is missing', '');
  const plural = (k, word) => (k === 1 ? word : word + 's');
  const verb = k => (k === 1 ? 'has' : 'have');
  md.push(`- ${n(noLocated)} of ${n(t.datasets)} ${plural(t.datasets, 'dataset')} ${verb(noLocated)} no located record in the published file (list only).`);
  md.push(`- ${n(noBoundary)} ${plural(noBoundary, 'dataset')} ${verb(noBoundary)} some located records without a parcel outline.`);
  md.push(`- ${n(withSource)} ${plural(withSource, 'dataset')} ${verb(withSource)} an official parcel source configured for the county. Nothing can be matched in the others, because none is configured.`);
  md.push(`- ${n(serverRows.length)} ${plural(serverRows.length, 'dataset')} ${verb(serverRows.length)} an owner-side audit (${serverRows.map(r => r.dataset).join(', ') || 'none'}). Its matches are not in the published file.`, '');
  md.push('## By state', '');
  md.push('| State | Datasets | Records | Located | Boundary | Unlocated | Located % | With an official source |', '|---|---|---|---|---|---|---|---|');
  for (const s of states) {
    const sr = rows.filter(r => r.state === s), st = totals(sr);
    md.push(`| ${cell(s)} | ${n(st.datasets)} | ${n(st.records)} | ${n(st.located)} | ${n(st.boundary)} | ${n(st.unlocated)} | ${pct(st.located, st.records)} | ${n(sr.filter(r => r.sources.length).length)} |`);
  }
  md.push('', '## By state and county', '');
  for (const s of states) {
    const sr = rows.filter(r => r.state === s);
    md.push(`### ${cell(s)} (${n(sr.length)} datasets)`, '');
    md.push('| County | Dataset | Records | Located | Boundary | Unlocated | Official source | Owner-side audit (matched / pending) | Florida registry |', '|---|---|---|---|---|---|---|---|---|');
    for (const r of sr) {
      md.push(`| ${cell(r.county)} | ${cell(r.dataset)} | ${n(r.records)} | ${n(r.located)} | ${n(r.boundary)} | ${n(r.unlocated)} | ${r.sources.length ? cell(r.sources.join(' + ')) : 'none'} | ${r.server ? n(r.server.matched) + ' / ' + n(r.server.pending) : '-'} | ${cell(r.florida) || '-'} |`);
    }
    md.push('');
  }
  const csvRows = [['state', 'county', 'dataset', 'records', 'located', 'boundary', 'unlocated', 'official_source', 'audit_matched', 'audit_boundary', 'audit_pending', 'florida_registry']];
  for (const r of rows) {
    csvRows.push([r.state, r.county, r.dataset, r.records, r.located, r.boundary, r.unlocated, r.sources.join(';') || 'none',
      r.server ? r.server.matched : '', r.server ? r.server.boundary : '', r.server ? r.server.pending : '', r.florida]);
  }
  return {md: md.join('\n') + '\n', csv: csvRows.map(row => row.map(csvCell).join(',')).join('\n') + '\n'};
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const rows = datasetRows();
  const {md, csv} = buildCoverage(rows);
  fs.mkdirSync(path.dirname(MD_FILE), {recursive: true});
  fs.writeFileSync(MD_FILE, md);
  fs.writeFileSync(CSV_FILE, csv);
  console.log('Wrote ' + rows.length + ' datasets to docs/location-coverage.md and docs/location-coverage.csv');
}
